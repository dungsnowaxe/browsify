use crate::rules::RulesFile;

/// Converts a Finicky `RulesFile` (`rules.json`) into a clean, commented Browsify `config.toml`.
pub fn rules_file_to_toml(rf: &RulesFile) -> String {
    let mut out = String::from("# Generated by `browsify migrate`\n");

    if !rf.default_browser.is_empty() {
        if !rf.default_profile.is_empty() {
            out.push_str(&format!(
                "default_browser = {{ name = {:?}, profile = {:?} }}\n\n",
                rf.default_browser, rf.default_profile
            ));
        } else {
            out.push_str(&format!("default_browser = {:?}\n\n", rf.default_browser));
        }
    } else {
        out.push_str("default_browser = \"com.apple.Safari\"\n\n");
    }

    if let Some(opts) = &rf.options {
        out.push_str("[options]\n");
        if let Some(v) = opts.keep_running {
            out.push_str(&format!("keep_running = {}\n", v));
        }
        if let Some(v) = opts.hide_icon {
            out.push_str(&format!("hide_icon = {}\n", v));
        }
        if let Some(v) = opts.log_requests {
            out.push_str(&format!("log_requests = {}\n", v));
        }
        if let Some(v) = opts.check_for_updates {
            out.push_str(&format!("check_for_updates = {}\n", v));
        }
        out.push('\n');
    }

    for r in &rf.rules {
        if r.match_patterns.is_empty() || r.browser.is_empty() {
            continue;
        }
        out.push_str("[[handlers]]\n");
        if r.match_patterns.len() == 1 {
            out.push_str(&format!("match = {:?}\n", r.match_patterns[0]));
        } else {
            out.push_str(&format!("match = {:?}\n", r.match_patterns));
        }
        if r.profile.is_empty() {
            out.push_str(&format!("browser = {:?}\n\n", r.browser));
        } else {
            out.push_str(&format!(
                "browser = {{ name = {:?}, profile = {:?} }}\n\n",
                r.browser, r.profile
            ));
        }
    }

    out
}
